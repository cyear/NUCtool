use crate::{Effect, HidError, KEY_COUNT, Profile, Result, Rgb};

/// Layout identifiers used by the NSS console. The service also reports code 88,
/// for which MobileKeyboardLedMgr has no physical-key map.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum KeyLayout {
    Us,
    Iso,
    Jis,
}

impl TryFrom<u8> for KeyLayout {
    type Error = Box<dyn std::error::Error>;

    fn try_from(code: u8) -> Result<Self> {
        match code {
            85 => Ok(Self::Us),
            86 => Ok(Self::Iso),
            87 => Ok(Self::Jis),
            _ => Err(HidError(format!(
                "原厂控制台没有布局 {code} 的键名映射，请用 126 槽配置"
            ))
            .into()),
        }
    }
}

impl KeyLayout {
    /// Physical names and zero-based slots in the service's KeyColor array.
    pub fn keys(self) -> &'static [(&'static str, &'static [usize])] {
        match self {
            Self::Us => US,
            Self::Iso => ISO,
            Self::Jis => JIS,
        }
    }
}

impl Profile {
    /// Set all slots belonging to a physical key and select UserMode.
    pub fn paint_key(&mut self, layout: KeyLayout, name: &str, color: Rgb) -> Result<()> {
        self.validate()?;
        let (_, slots) = layout
            .keys()
            .iter()
            .find(|(key, _)| key.eq_ignore_ascii_case(name))
            .ok_or_else(|| HidError(format!("该布局没有名为 {name} 的键")))?;
        self.key_colors.resize(KEY_COUNT, [0; 3]);
        for &slot in *slots {
            self.key_colors[slot] = color;
        }
        self.effect = Effect::UserMode;
        Ok(())
    }
}

